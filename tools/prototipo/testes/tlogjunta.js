// Cliques seguidos na temperatura viram um log só; voltar ao valor de antes não deixa log; passados 7 s, é outro log.
const TMP=require('path').join(__dirname,'..','saida')+'/';require('fs').mkdirSync(TMP+'t_logjunta',{recursive:true});
const {chromium}=require('playwright');
const L=require('path').join(__dirname,'..','libs','l')+'/';const F=require('path').join(__dirname,'..','saida','bkm-terrenos.html');const OUT=TMP+'t_logjunta/';
(async()=>{const b=await chromium.launch();const errs=[];let falhas=0;
const ok=(c,m)=>{console.log((c?'ok   ':'FALHOU ')+m);if(!c)falhas++};
const ctx=await b.newContext({viewport:{width:1440,height:900},deviceScaleFactor:2});
await ctx.route('**/*',r=>{const u=r.request().url();if(u.startsWith('file://')&&u.endsWith('.html'))return r.fulfill({path:F,contentType:'text/html; charset=utf-8'});
  if(/leaflet.js|jszip/.test(u))return r.fulfill({path:L+(u.includes('leaflet')?'leaflet.js':'jszip.min.js'),contentType:'application/javascript'});
  if(/cartocdn|openstreetmap|arcgisonline/.test(u))return r.fulfill({path:require('path').join(__dirname,'tile.png'),contentType:'image/png'});return r.abort()});
const p=await ctx.newPage();p.on('pageerror',e=>errs.push(e.message));
await p.goto('file://'+F);await p.evaluate(()=>localStorage.clear());await p.reload();await p.waitForTimeout(400);
await p.evaluate(()=>document.querySelector('[data-a=nav][data-r=terrenos]').click());await p.waitForTimeout(150);
await p.evaluate(()=>{[...document.querySelectorAll('[data-a=abrir]')].find(x=>x.textContent.includes('Barão')).click()});await p.waitForTimeout(400);
const ter=()=>p.evaluate(()=>JSON.parse(localStorage.getItem('bkm-terrenos-prototipo-v9')).terrenos.find(t=>t.nome.includes('Barão')));
const temp=async n=>{const v=(await ter()).neg.temp===n?0:n;await p.evaluate(v=>document.querySelector(`[data-a=temp][data-v="${v}"]`).click(),v);await p.waitForTimeout(80)};
const logs=async()=>(await ter()).hist.filter(h=>/^Temperatura/.test(h.txt)).map(h=>h.txt);
const t0=(await ter()).neg.temp;const n0=(await logs()).length;
const outros=[1,2,3,4,5].filter(x=>x!==t0);
await temp(outros[0]);await temp(outros[1]);await temp(outros[2]);
let L1=await logs();ok(L1.length===n0+1,`três cliques seguidos, um log: ${L1.slice(n0).join(' | ')}`);
ok(L1[L1.length-1].includes(`${t0}/5 → ${outros[2]}/5`),'o log vai do valor de antes ao final');
const pis=await p.evaluate(async()=>{const el=[...document.querySelectorAll('.pn-lt')].find(x=>x.textContent.startsWith('Temperatura'));el.closest('.pn-log').click();await new Promise(r=>setTimeout(r,1300));return [...document.querySelectorAll('.pisca')].map(x=>x.innerText.slice(0,30))});
ok(pis.length>0,`clicar no log juntado acende a temperatura na ficha: ${pis.join(' | ')}`);
await p.screenshot({path:OUT+'juntado.png'});
await temp(t0);
L1=await logs();ok(L1.length===n0,'voltou ao valor de antes: o log some');
await temp(outros[0]);
await p.evaluate(()=>{const d=Date.now;Date.now=()=>d()+8000});
await temp(outros[1]);
L1=await logs();ok(L1.length===n0+2,`passados 7 s, outro log: ${L1.slice(n0).join(' | ')}`);
await p.screenshot({path:OUT+'painel.png',clip:{x:1080,y:60,width:360,height:600}});
console.log('ERROS',errs);await b.close();process.exit(falhas||errs.length?1:0)})();
